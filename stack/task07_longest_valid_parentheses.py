"""Стек, задача 7. Довжина найдовшого правильного підрядка з дужок."""


def longest_valid_parentheses(s):
    """Повертає довжину найдовшого правильно сформованого підрядка дужок."""
    # У стеку - індекси відкритих "(" і на дні індекс позиції
    # перед початком поточного правильного підрядка
    stack = [-1]
    best = 0
    for i, ch in enumerate(s):
        if ch == "(":
            stack.append(i)
        else:
            stack.pop()
            if not stack:
                # Зайва ")" - правильний підрядок далі може початися лише після неї
                stack.append(i)
            else:
                best = max(best, i - stack[-1])
    return best
